<script>
   document.addEventListener("DOMContentLoaded", () => {
   
    const timelinePath = document.getElementById("timelinePath");
    const timelineContainer = document.getElementById("timelineAnimation");
   
    const pathLength = timelinePath.getTotalLength();
   
    /* ==========================================
    SVG LINE SETUP
    ========================================== */
   
    timelinePath.style.strokeDasharray = pathLength;
    timelinePath.style.strokeDashoffset = -pathLength;
   
    /* ==========================================
    INTERSECTION OBSERVER
    ========================================== */
   
    const observer = new IntersectionObserver((entries) => {
   
        entries.forEach((entry) => {
   
            if (entry.isIntersecting) {
   
                /* =========================
                LINE ANIMATION
                ========================= */
   
                timelinePath.style.transition =
                    "stroke-dashoffset 2.5s ease-in-out";
   
                timelinePath.style.strokeDashoffset = "0";
   
                /* =========================
                GROUP ANIMATION
                ========================= */
   
                const animationGroups = [
                    {
                        selector: ".js-group-1",
                        delay: 400
                    },
                    {
                        selector: ".js-group-2",
                        delay: 900
                    },
                    {
                        selector: ".js-group-3",
                        delay: 1400
                    },
                    {
                        selector: ".js-group-4",
                        delay: 1900
                    }
                ];
   
                animationGroups.forEach((group) => {
   
                    setTimeout(() => {
   
                        document.querySelectorAll(group.selector)
                            .forEach((element) => {
   
                                element.classList.add("is-visible");
   
                            });
   
                    }, group.delay);
   
                });
   
                /* =========================
                CAP ANIMATION
                ========================= */
   
                setTimeout(() => {
   
                    document
                        .querySelector(".timeline__cap")
                        .classList.add("is-visible");
   
                }, 2500);
   
                observer.unobserve(entry.target);
   
            }
   
        });
   
    }, {
        threshold: 0.2
    });
   
    observer.observe(timelineContainer);
   
   });
</script>

<script>
window.addEventListener("load", function () {
    if (sessionStorage.getItem("scrollToContact") === "true") {
        const target = document.getElementById("consultation-form");

        if (target) {
            // Small timeout ensures we override the browser's default jump
            setTimeout(() => {
                const offset = 140; 
                const elementPosition = target.getBoundingClientRect().top + window.pageYOffset;
                const offsetPosition = elementPosition - offset;

                window.scrollTo({
                    top: offsetPosition,
                    behavior: "smooth"
                });
                
                sessionStorage.removeItem("scrollToContact");
            }, 100); 
        }
    }
});
</script>

